"""Copy the forest (playtreeone, the `web` submodule) into ext/tree, ready to
load as an extension with no build step.

    git submodule update --remote web   # (optional) take the latest playtreeone
    python tools/sync_forest.py

Extensions (Manifest V3) can't load code from a CDN or use inline import maps,
so the playtreeone page is copied without its import map, its bare imports
('three', 'lil-gui', OrbitControls) are pointed at ext/tree/vendor, and our
own modules (bridge.js, chatter.js) are added to the page. The copied files
in ext/tree/src and ext/tree/index.html are generated: change them in
playtreeone, then sync.
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB, TREE = ROOT / 'web', ROOT / 'ext' / 'tree'
IMPORTS = {
    'three': '../vendor/three.module.js',
    'three/addons/controls/OrbitControls.js': '../vendor/OrbitControls.js',
    'lil-gui': '../vendor/lil-gui.esm.min.js',
}


def rewrite(text, table):
    def sub(m):
        return m.group(1) + table.get(m.group(2), m.group(2)) + m.group(3)
    return re.sub(r"""(from\s+['"])([^'"]+)(['"])""", sub, text)


def main():
    if not (WEB / 'src' / 'main.js').exists():
        raise SystemExit('web/ is empty: run  git submodule update --init')
    src = TREE / 'src'
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)
    for js in (WEB / 'src').glob('*.js'):
        (src / js.name).write_text(rewrite(js.read_text('utf-8'), IMPORTS), 'utf-8', newline='\n')

    html = (WEB / 'index.html').read_text('utf-8')
    html, n = re.subn(r'<script type="importmap">.*?</script>\s*', '', html, flags=re.S)
    if n != 1:
        raise SystemExit('index.html: import map not found')
    html = html.replace('<script type="module" src="src/main.js"></script>',
                        '<script type="module" src="src/main.js"></script>\n'
                        '<script type="module" src="bridge.js"></script>\n'
                        '<script type="module" src="chatter.js"></script>')
    html = html.replace('<head>', '<head>\n<!-- Generated by tools/sync_forest.py from playtreeone (web/index.html). -->', 1)
    (TREE / 'index.html').write_text(html, 'utf-8', newline='\n')

    orbit = TREE / 'vendor' / 'OrbitControls.js'
    orbit.write_text(rewrite(orbit.read_text('utf-8'), {'three': './three.module.js'}), 'utf-8', newline='\n')
    shutil.copy(WEB / 'licenses' / 'd3-celestial.txt', ROOT / 'ext' / 'licenses' / 'd3-celestial.txt')

    left = [str(p.relative_to(ROOT)) for p in TREE.rglob('*.js')
            if re.search(r"""from\s+['"](three|lil-gui)['"/]""", p.read_text('utf-8'))]
    if left:
        raise SystemExit(f'bare imports left in: {left}')
    print(f'synced playtreeone into {TREE.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
